    private static function article(
        string $category,
        string $title,
        string $slug,
        string $excerpt,
        string $lead,
        array $steps,
        array $notes = []
    ): array {
        $content = '<p>' . self::escape($lead) . '</p>'
            . '<h2>Что сделать</h2><ol>'
            . implode('', array_map(static fn(string $step): string => '<li>' . self::escape($step) . '</li>', $steps))
            . '</ol>';
        if ($notes !== []) {
            $content .= '<h2>Важно</h2><ul>'
                . implode('', array_map(static fn(string $note): string => '<li>' . self::escape($note) . '</li>', $notes))
                . '</ul>';
        }

        return [
            'category_slug' => $category,
            'title' => $title,
            'slug' => $slug,
            'excerpt' => $excerpt,
            'content' => $content,
        ];
    }

    private static function pluginAvailable(string $slug): bool
    {
        return is_file(dirname(__DIR__, 2) . '/plugins/' . $slug . '/plugin.json');
    }

    private static function escape(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
